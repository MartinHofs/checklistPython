"""Provided tests for Part 2 (roster.py). Run: python -m unittest -v test_roster
Do not edit this file. A failing test means roster.py needs a fix."""
import os
import tempfile
import unittest

import roster


class TestRoster(unittest.TestCase):
    def setUp(self):
        folder = tempfile.mkdtemp()
        self.db = os.path.join(folder, "test_guild.db")
        roster.create_table(self.db)
        roster.add_hero(self.db, "Brenna", "Warrior", 3)
        roster.add_hero(self.db, "Corwin", "Mage", 5)
        roster.add_hero(self.db, "Dax", "Rogue", 2)
        roster.add_hero(self.db, "Elsbeth", "Mage", 4)

    def test_heroes_by_level_highest_first(self):
        self.assertEqual(
            roster.heroes_by_level(self.db),
            [("Corwin", "Mage", 5), ("Elsbeth", "Mage", 4),
             ("Brenna", "Warrior", 3), ("Dax", "Rogue", 2)],
        )

    def test_heroes_in_role(self):
        self.assertEqual(
            roster.heroes_in_role(self.db, "Mage"),
            [("Corwin", 5), ("Elsbeth", 4)],
        )

    def test_heroes_in_role_none(self):
        self.assertEqual(roster.heroes_in_role(self.db, "Bard"), [])

    def test_average_level(self):
        self.assertEqual(roster.average_level(self.db), 3.5)

    def test_average_level_empty_table(self):
        folder = tempfile.mkdtemp()
        empty = os.path.join(folder, "empty.db")
        roster.create_table(empty)
        self.assertEqual(roster.average_level(empty), 0)

    def test_count_by_role(self):
        self.assertEqual(
            roster.count_by_role(self.db),
            {"Warrior": 1, "Mage": 2, "Rogue": 1},
        )

    def test_level_up_changes_only_that_hero(self):
        roster.level_up(self.db, "Dax")
        levels = {n: lv for n, r, lv in roster.heroes_by_level(self.db)}
        self.assertEqual(levels["Dax"], 3)
        self.assertEqual(levels["Brenna"], 3)
        self.assertEqual(levels["Corwin"], 5)

    def test_retire_removes_only_that_hero(self):
        roster.retire(self.db, "Brenna")
        names = [n for n, r, lv in roster.heroes_by_level(self.db)]
        self.assertEqual(sorted(names), ["Corwin", "Dax", "Elsbeth"])

    def test_name_with_quote_is_stored_safely(self):
        roster.add_hero(self.db, "O'Neil", "Rogue", 1)
        names = [n for n, r, lv in roster.heroes_by_level(self.db)]
        self.assertIn("O'Neil", names)


if __name__ == "__main__":
    unittest.main()
