"""Provided tests for Part 4 (creatures.py). Run: python -m unittest -v test_creatures
Do not edit this file. A failing test means creatures.py needs a fix."""
import unittest

import creatures


class TestCreatures(unittest.TestCase):
    def test_base_creature(self):
        c = creatures.Creature("Thing", 10)
        self.assertEqual(c.name, "Thing")
        self.assertEqual(c.health, 10)
        self.assertEqual(c.attack(), 1)
        self.assertEqual(c.describe(), "Thing the creature (10 HP)")

    def test_goblin_inherits_and_overrides(self):
        g = creatures.Goblin("Grix")
        self.assertIsInstance(g, creatures.Creature)
        self.assertEqual(g.health, 20)
        self.assertEqual(g.attack(), 4)
        self.assertEqual(g.describe(), "Grix the goblin (20 HP)")

    def test_dragon_extra_attribute_and_describe(self):
        d = creatures.Dragon("Smaug")
        self.assertIsInstance(d, creatures.Creature)
        self.assertEqual(d.health, 100)
        self.assertEqual(d.attack(), 20)
        self.assertEqual(d.breath, "fire")
        self.assertEqual(d.describe(), "Smaug the dragon (100 HP), breathing fire")

    def test_slime_uses_inherited_attack(self):
        s = creatures.Slime("Blob")
        self.assertEqual(s.health, 8)
        self.assertEqual(s.attack(), 1)

    def test_species_is_a_class_attribute(self):
        self.assertEqual(creatures.Creature.species, "creature")
        self.assertEqual(creatures.Goblin.species, "goblin")
        self.assertEqual(creatures.Dragon.species, "dragon")
        self.assertEqual(creatures.Slime.species, "slime")

    def test_health_is_per_creature(self):
        a = creatures.Goblin("A")
        b = creatures.Goblin("B")
        a.take_damage(5)
        self.assertEqual(a.health, 15)
        self.assertEqual(b.health, 20)

    def test_health_never_below_zero(self):
        g = creatures.Goblin("Grix")
        g.take_damage(500)
        self.assertEqual(g.health, 0)
        self.assertFalse(g.is_alive())

    def test_total_attack_mixed_list(self):
        party = [creatures.Goblin("G"), creatures.Dragon("D"), creatures.Slime("S")]
        self.assertEqual(creatures.total_attack(party), 25)

    def test_total_attack_empty_list(self):
        self.assertEqual(creatures.total_attack([]), 0)


if __name__ == "__main__":
    unittest.main()
