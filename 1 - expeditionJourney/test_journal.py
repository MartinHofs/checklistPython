"""Provided tests for Part 1 (journal.py). Run: python -m unittest -v test_journal
Do not edit this file. A failing test means journal.py needs a fix."""
import os
import tempfile
import unittest

import journal


class TestJournal(unittest.TestCase):
    def setUp(self):
        folder = tempfile.mkdtemp()
        self.path = os.path.join(folder, "journal.txt")

    def test_add_entry_creates_one_line(self):
        journal.add_entry(self.path, "Mushroom Hall", 15)
        with open(self.path) as f:
            self.assertEqual(f.read(), "Mushroom Hall,15\n")

    def test_add_entry_appends(self):
        journal.add_entry(self.path, "Mushroom Hall", 15)
        journal.add_entry(self.path, "Echo Chamber", 5)
        with open(self.path) as f:
            self.assertEqual(f.read(), "Mushroom Hall,15\nEcho Chamber,5\n")

    def test_read_entries_returns_tuples_with_int_gold(self):
        journal.add_entry(self.path, "Mushroom Hall", 15)
        journal.add_entry(self.path, "Echo Chamber", 5)
        self.assertEqual(
            journal.read_entries(self.path),
            [("Mushroom Hall", 15), ("Echo Chamber", 5)],
        )

    def test_read_entries_missing_file_gives_empty_list(self):
        self.assertEqual(journal.read_entries(self.path), [])

    def test_total_gold(self):
        journal.add_entry(self.path, "Mushroom Hall", 15)
        journal.add_entry(self.path, "Crystal Gallery", 40)
        self.assertEqual(journal.total_gold(self.path), 55)

    def test_total_gold_missing_file_is_zero(self):
        self.assertEqual(journal.total_gold(self.path), 0)


if __name__ == "__main__":
    unittest.main()
