"""Provided tests for Part 5 (caves.py). Run: python -m unittest -v test_caves
Do not edit this file. A failing test means caves.py needs a fix."""
import unittest

import caves


def room(name, gold, tunnels=None):
    return {"name": name, "gold": gold, "tunnels": tunnels or []}


class TestCaves(unittest.TestCase):
    def setUp(self):
        self.small = room("Entrance", 0, [
            room("Left", 10),
            room("Right", 20, [room("Deep", 100)]),
        ])
        self.single = room("Lonely", 7)

    def test_count_rooms_single(self):
        self.assertEqual(caves.count_rooms(self.single), 1)

    def test_count_rooms_nested(self):
        self.assertEqual(caves.count_rooms(self.small), 4)

    def test_total_gold_single(self):
        self.assertEqual(caves.total_gold(self.single), 7)

    def test_total_gold_nested(self):
        self.assertEqual(caves.total_gold(self.small), 130)

    def test_depth_single(self):
        self.assertEqual(caves.depth(self.single), 1)

    def test_depth_nested(self):
        self.assertEqual(caves.depth(self.small), 3)

    def test_find_room_at_top(self):
        self.assertIs(caves.find_room(self.small, "Entrance"), self.small)

    def test_find_room_deep(self):
        found = caves.find_room(self.small, "Deep")
        self.assertEqual(found["gold"], 100)

    def test_find_room_missing(self):
        self.assertIsNone(caves.find_room(self.small, "Treasury"))


if __name__ == "__main__":
    unittest.main()
