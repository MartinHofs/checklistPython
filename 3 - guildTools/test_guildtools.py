"""Provided tests for Part 3 (guildtools package). Run: python -m unittest -v test_guildtools
Do not edit this file. A failing test means the package needs a fix."""
import unittest

from guildtools import dice, loot


class TestDice(unittest.TestCase):
    def test_roll_stays_in_range(self):
        for _ in range(200):
            self.assertIn(dice.roll(6), range(1, 7))

    def test_roll_many_length(self):
        self.assertEqual(len(dice.roll_many(5, 20)), 5)

    def test_roll_many_values_in_range(self):
        for value in dice.roll_many(100, 4):
            self.assertIn(value, [1, 2, 3, 4])

    def test_dice_functions_have_docstrings(self):
        self.assertTrue(dice.roll.__doc__)
        self.assertTrue(dice.roll_many.__doc__)


class TestLoot(unittest.TestCase):
    def test_split_even(self):
        self.assertEqual(loot.split_loot(100, 4), 25)

    def test_split_rounds_up(self):
        self.assertEqual(loot.split_loot(100, 3), 34)

    def test_bonus_gold_is_a_multiple_of_ten(self):
        for _ in range(200):
            bonus = loot.bonus_gold()
            self.assertIn(bonus, [10, 20, 30, 40, 50, 60])

    def test_loot_functions_have_docstrings(self):
        self.assertTrue(loot.split_loot.__doc__)
        self.assertTrue(loot.bonus_gold.__doc__)


if __name__ == "__main__":
    unittest.main()
